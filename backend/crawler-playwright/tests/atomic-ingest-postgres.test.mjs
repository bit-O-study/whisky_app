import { PGlite } from '@electric-sql/pglite';
import { readFile } from 'node:fs/promises';
import { test, before, beforeEach, after } from 'node:test';
import assert from 'node:assert/strict';

const db = new PGlite();
before(async () => {
  await db.exec(`
    create role anon; create role authenticated; create role service_role;
    create table public.liquor(id bigint primary key);
    create table public.liquor_price(id bigint generated by default as identity primary key,
      liquor_id bigint references liquor(id),source text,current_price integer,original_price integer,
      crawled_at timestamp not null,unique(liquor_id,source));
    create table public.liquor_url(id bigint generated by default as identity primary key,
      liquor_id bigint references liquor(id),source text,product_url text,image_url text);
    create table public.liquor_price_history(id bigint generated by default as identity primary key,
      liquor_id bigint references liquor(id),source text,current_price integer,original_price integer,crawled_at timestamptz);
    grant select,insert,update on all tables in schema public to service_role;
    grant usage on all sequences in schema public to service_role;
  `);
  await db.exec(await readFile(new URL('../sql/ingest_existing_liquor.sql', import.meta.url), 'utf8'));
});
beforeEach(async () => {
  await db.exec(`reset role;
    truncate liquor,liquor_price,liquor_url,liquor_price_history restart identity cascade;
    insert into liquor values(1);
    insert into liquor_price(liquor_id,source,current_price,original_price,crawled_at)
      values(1,'LOTTEON',144800,144800,'2026-09-03 13:56:24');
    insert into liquor_url(liquor_id,source,product_url) values(1,'LOTTEON','old');
    set role service_role;`);
});
after(() => db.close());
const payload = () => ({ liquorId: 1, source: 'LOTTEON', currentPrice: 149800, originalPrice: 149800,
  observedAt: new Date().toISOString(), productUrl: 'https://www.lotteon.com/p/product/LM5000281005409', imageUrl: '' });
const call = value => db.query('select public.ingest_existing_liquor($1::jsonb)', [JSON.stringify(value)]);

test('real Postgres transaction updates price, link and history at the same instant', async () => {
  const value = payload();
  await call(value);
  const { rows } = await db.query(`select p.current_price,
    p.crawled_at = ($1::timestamptz at time zone 'UTC') as same_time,
    (select count(*) from liquor_price_history where crawled_at=$1::timestamptz) as histories,
    (select product_url from liquor_url limit 1) as url from liquor_price p`, [value.observedAt]);
  assert.equal(rows[0].current_price, 149800);
  assert.equal(rows[0].same_time, true);
  assert.equal(Number(rows[0].histories), 1);
  assert.equal(rows[0].url, value.productUrl);
});

test('failure after the price statement rolls the entire RPC back', async () => {
  await assert.rejects(call({ ...payload(), productUrl: 'https://invalid.example/product' }), /invalid_lotteon_url/);
  assert.equal((await db.query('select current_price from liquor_price')).rows[0].current_price, 144800);
  assert.equal((await db.query('select product_url from liquor_url')).rows[0].product_url, 'old');
  assert.equal(Number((await db.query('select count(*) from liquor_price_history')).rows[0].count), 0);
});

test('zero, negative and missing prices never damage saved prices', async () => {
  for (const currentPrice of [0, -1, null]) await assert.rejects(call({ ...payload(), currentPrice }), /invalid_current_price/);
  assert.equal((await db.query('select current_price from liquor_price')).rows[0].current_price, 144800);
});

test('replaying the same observation does not duplicate price history', async () => {
  const value = payload();
  await call(value); await call(value);
  assert.equal(Number((await db.query('select count(*) from liquor_price_history')).rows[0].count), 1);
});

test('an older observation cannot replace a newer saved price', async () => {
  const value = payload();
  await call(value);
  await assert.rejects(call({ ...value, currentPrice: 100, observedAt: new Date(Date.parse(value.observedAt) - 1000).toISOString() }), /stale_observation/);
  assert.equal((await db.query('select current_price from liquor_price')).rows[0].current_price, 149800);
});

test('anon and authenticated cannot call the server-only function', async () => {
  for (const role of ['anon', 'authenticated']) {
    await db.exec('reset role; set role ' + role);
    await assert.rejects(call(payload()), /permission denied/);
  }
});

test('missing masters and invalid sources are rejected', async () => {
  await assert.rejects(call({ ...payload(), liquorId: 999 }), /existing_liquor_required/);
  await assert.rejects(call({ ...payload(), source: 'UNKNOWN' }), /invalid_source/);
});
