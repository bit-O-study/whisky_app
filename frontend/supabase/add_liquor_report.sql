-- 사용자 "알려 주기"(가격·링크 오류 신고). 개인정보 없이 상품·판매처·사유·시각만 남긴다.
-- 서버(Next.js /api/liquors/[id]/report, service_role)에서만 기록/조회한다. RLS 잠금(익명 공개 없음).
-- 테이블이 없으면 상세 화면의 "알려 주기" 버튼은 자동으로 숨는다.
-- Supabase SQL 에디터에서 1회 실행:
--   https://supabase.com/dashboard/project/jeqvxzkvumkiraclauvo/sql/new

create table if not exists public.liquor_report (
    id bigint generated by default as identity primary key,
    liquor_id bigint not null references public.liquor (id) on delete cascade,
    source text,
    reason text not null check (reason in ('wrong_product', 'wrong_price', 'sold_out', 'broken_link')),
    resolved_at timestamptz,
    created_at timestamptz not null default now()
);

create index if not exists idx_liquor_report_open
    on public.liquor_report (created_at desc) where resolved_at is null;

alter table public.liquor_report enable row level security;
-- 정책을 열지 않으므로 anon/authenticated 는 접근 불가. service_role(서버)만 가능.
